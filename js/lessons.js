function verticalStatic(top, bottom, result, carry) {
  const w = Math.max(top.length, bottom.length, result.length) + 1;
  return `<div class="vertical small" dir="ltr">${carry ? `<div class="vcarry">${carry.padStart(w)}</div>` : ''}<div>${top.padStart(w)}</div><div>${bottom.padStart(w)}</div><div class="vline"></div><div class="vres">${result.padStart(w)}</div></div>`;
}

