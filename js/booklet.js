'use strict';
// The printed practice booklet ("חוברת תרגול במתמטיקה") as interactive questions.
// Each page = one topic. Questions keep the booklet's numbers so they match the paper.

function buildBooklet() {
  const pages = [];
  const page = (topic, title, qs) => pages.push({ id: `p${pages.length + 1}`, topic, title, qs: qs.map((q, i) => ({ ...q, id: `p${pages.length + 1}-${i + 1}` })) });
  const cmp = (l, r) => Q.compare(l, r);

  page('place', '1. מבנה המספר העשרוני', [
    ...[3407, 5060, 9999, 7200, 2315, 10000].map((n) => Q.wordsToDigits(n)),
    ...[4628, 7035, 9400, 1009].map((n) => Q.digitsToWords(n)),
    Q.digitValue(6437, 2), Q.digitValue(8152, 3), Q.digitValue(3906, 2), Q.digitValue(5071, 1), Q.digitValue(2345, 0),
    Q.expansionBlanks(4385), Q.expansionBlanks(7042), Q.expandedToNum([6000, 200, 9]), Q.expandedToNum([3000, 50]),
    ...[3499, 7000, 4090, 9999, 1010, 600].map((n) => Q.succPred(n)),
    Q.selectNumbers('בחרי את כל המספרים <b>הזוגיים</b>:', [346, 1257, 8000, 4443, 7019, 2598, 65, 990], (v) => v % 2 === 0, 'זוגי = ספרת היחידות היא 0, 2, 4, 6 או 8.', 'הזוגיים'),
    Q.selectNumbers('בחרי את כל המספרים ה<b>תלת־ספרתיים</b>:', [7, 48, 305, 1200, 99, 6004, 100, 10000], (v) => v >= 100 && v < 1000, 'תלת־ספרתי = יש בו בדיוק 3 ספרות.', 'התלת־ספרתיים'),
    Q.selectNumbers('בחרי את כל המספרים ה<b>ארבע־ספרתיים</b>:', [7, 48, 305, 1200, 99, 6004, 100, 10000], (v) => v >= 1000 && v < 10000, 'ארבע־ספרתי = יש בו בדיוק 4 ספרות.', 'הארבע־ספרתיים'),
    Q.selectNumbers('בחרי את כל המספרים ה<b>דו־ספרתיים</b>:', [7, 48, 305, 1200, 99, 6004, 100, 10000], (v) => v >= 10 && v < 100, 'דו־ספרתי = יש בו בדיוק 2 ספרות.', 'הדו־ספרתיים'),
    Q.placeRiddle('המספר הזוגי הגדול ביותר שהוא תלת־ספרתי:', 998, 'התלת־ספרתי הגדול ביותר הוא 999 (אי־זוגי), ולכן הזוגי הגדול ביותר הוא <b>998</b>.'),
    Q.placeRiddle('המספר האי־זוגי הקטן ביותר שהוא דו־ספרתי:', 11, 'הדו־ספרתי הקטן ביותר הוא 10 (זוגי), ולכן האי־זוגי הקטן ביותר הוא <b>11</b>.'),
    Q.placeRiddle('המספר הקטן ביותר שיש בו 4 ספרות:', 1000, 'התשובה: <b>1,000</b>.'),
    Q.fromDigits([3, 8, 1, 6], true), Q.fromDigits([3, 8, 1, 6], false),
  ]);

  page('line', '2. מיקום מספרים על ישר המספרים', [
    Q.numberLine(0, 10, 11, [2, 5, 8]),
    Q.numberLine(0, 100, 11, [1, 4, 6, 9]),
    Q.numberLine(2000, 100, 11, [2, 3, 6, 8]),
    Q.numberLine(4000, 250, 5, [1, 3]),
    Q.numberLine(0, 1000, 11, [1, 3, 4, 6, 7, 9]),
    Q.midpoint(300, 500), Q.midpoint(2000, 3000), Q.midpoint(4600, 4800),
    Q.closer(480, 0, 1000), Q.closer(6700, 6000, 7000),
  ]);

  page('compare', '3. אי־שוויונים (> < =)', [
    cmp(3456, 3465), cmp(7009, 7090), cmp(5000, 4999), cmp([600, '+', 40], 640),
    cmp([8, '×', 7], 60), cmp([1000, '−', 1], 999), cmp(2354, 2345), cmp([9, '×', 6], [6, '×', 9]),
    cmp([4000, '+', 300, '+', 5], 4350), cmp([50, '×', 4], 210), cmp(10000, 9999), cmp(3070, 3007),
    cmp([125, '+', 125], 250), cmp([900, '−', 90], 801), cmp([7, '×', 8], [8, '×', 8, '−', 8]), cmp([72, '÷', 8], [3, '×', 3]),
    Q.missingDigitCompare('3,_45 > 3,845', [9], 'האלפים שווים (3). כדי שהמספר יהיה גדול יותר, ספרת המאות צריכה להיות גדולה מ־8 – רק <b>9</b>.'),
    Q.missingDigitCompare('5,1_0 < 5,120', [0, 1], 'האלפים והמאות שווים. ספרת העשרות צריכה להיות קטנה מ־2 – <b>0 או 1</b>.'),
    Q.missingDigitCompare('6,0_8 = 6,078', [7], 'המספרים צריכים להיות זהים – הספרה היא <b>7</b>.'),
    Q.orderNumbers([4506, 4065, 4650, 4560, 4056]),
  ]);

  page('seq', '4. סדרות חשבוניות', [
    Q.seqBlanks([2, 5, 8, null, null, null], 3),
    Q.seqBlanks([100, 90, 80, null, null, null], -10),
    Q.seqBlanks([25, 50, 75, null, null, null], 25),
    Q.seqBlanks([1000, 1250, 1500, null, null, null], 250),
    Q.seqBlanks([96, 88, 80, null, null, null], -8),
    Q.seqBlanks([3400, 3300, 3200, null, null, null], -100),
    Q.seqBlanks([7, null, 21, null, 35, null], 7),
    Q.seqBlanks([null, 15, null, 33, 42], 9),
    Q.seqRule([4, 10, 16, 22], 6),
    Q.seqBlanks([4, 10, 16, 22, null], 6),
    Q.seqAppears(5, 5, 50), Q.seqAppears(5, 5, 72),
    Q.seqNth(3, 4, 10),
    Q.seqNth(200, -25, 5, `סדרה מתחילה ב־${M('200')} ויורדת ב־${M('25')} בכל צעד. מה המספר ה<b>חמישי</b> בסדרה?`),
  ]);

  const v = (a, b, op) => Q.vertical(a, b, op);
  page('addsub', '5. חיבור וחיסור במאונך', [
    v(345, 234, '+'), v(1256, 2431, '+'), v(478, 365, '+'), v(2689, 1547, '+'), v(3975, 4068, '+'), v(5708, 2896, '+'),
    v(789, 456, '−'), v(5684, 2431, '−'), v(702, 358, '−'), v(4000, 1256, '−'), v(6305, 2478, '−'), v(8120, 3465, '−'),
    Q.detective(503, 278, 335, 'יואב'),
    { ...v(503, 278, '−'), prompt: 'מה התשובה הנכונה לתרגיל של יואב?' },
    Q.checkBySum(4000, 1256),
  ]);

  page('mult', '6. כפל במאונך', [
    v(23, 3, '×'), v(47, 5, '×'), v(68, 4, '×'), v(93, 7, '×'), v(56, 8, '×'), v(79, 6, '×'),
    v(214, 2, '×'), v(325, 4, '×'), v(506, 7, '×'), v(487, 3, '×'), v(739, 5, '×'), v(864, 9, '×'),
    Q.multMissing(4, 3, 6),
  ]);

  page('order', '7. סדר פעולות חשבון', [
    ...[
      [4, '+', 3, '×', 5], [20, '−', 12, '÷', 4], ['(', 8, '+', 2, ')', '×', 6], [36, '÷', '(', 9, '−', 3, ')'],
      [5, '×', 4, '+', 3, '×', 2], [50, '−', '(', 20, '+', 15, ')'], [100, '−', 8, '×', 9], [7, '×', '(', 10, '−', 4, ')', '+', 2],
      [48, '÷', 6, '+', 6, '×', 3], ['(', 25, '−', 5, ')', '÷', 4, '×', 3], [9, '+', 6, '÷', 3, '−', 2], [3, '×', '(', 4, '+', 5, ')', '−', '(', 12, '−', 2, ')'],
    ].map((t) => Q.evalExpr(t)),
    Q.parens([6, '+', 4, '×', 3], 30), Q.parens([20, '−', 8, '−', 2], 14), Q.parens([2, '×', 5, '+', 5], 20), Q.parens([18, '÷', 3, '+', 3], 3),
    Q.trueFalseExpr([10, '−', 2, '×', 3], 24), Q.trueFalseExpr([6, '+', 6, '÷', 6], 7), Q.trueFalseExpr([4, '×', '(', 3, '+', 2, ')'], 14),
  ]);

  page('word', '8. שאלות מילוליות', [
    Q.word('בספריית בית הספר היו 2,450 ספרים. השנה קנו עוד 375 ספרים. כמה ספרים יש בספרייה עכשיו?', 2825, '2,450 + 375 = 2,825', '<b>"עוד"</b> – חיבור.', 'ספרים'),
    Q.word('בחנות היו 1,500 בקבוקי מים. ביום שישי מכרו 638 בקבוקים. כמה בקבוקים נשארו?', 862, '1,500 − 638 = 862', '<b>"נשארו"</b> – חיסור.', 'בקבוקים'),
    Q.word('בכל קופסה יש 6 עפרונות. כמה עפרונות יש ב־48 קופסאות?', 288, '48 × 6 = 288', '<b>"בכל"</b> קופסה אותו מספר – כפל.', 'עפרונות'),
    Q.word('72 תלמידים יוצאים לטיול ומתחלקים שווה בשווה ל־8 קבוצות. כמה תלמידים בכל קבוצה?', 9, '72 ÷ 8 = 9', '<b>"שווה בשווה"</b> – חילוק.', 'תלמידים'),
    Q.word('תמר קנתה 3 חולצות ב־45 ₪ כל אחת, ומכנסיים ב־89 ₪. כמה שילמה בסך הכול?', 224, '3 × 45 + 89 = 135 + 89 = 224', 'קודם כמה עלו החולצות (כפל), ואז מוסיפים את המכנסיים.', '₪'),
    Q.word('לאורי היו 350 ₪. סבתא נתנה לו עוד 125 ₪, ואז הוא קנה משחק ב־260 ₪. כמה כסף נשאר לו?', 215, '350 + 125 − 260 = 215', '"נתנה לו עוד" – חיבור. "קנה" – חיסור.', '₪'),
    Q.word('באולם 24 שורות, ובכל שורה 9 כיסאות. 150 כיסאות תפוסים. כמה כיסאות פנויים?', 66, '24 × 9 − 150 = 216 − 150 = 66', 'קודם כמה כיסאות יש בכלל (כפל), ואז מורידים את התפוסים.', 'כיסאות'),
    Q.wordMulti('שירה קראה 18 עמודים בכל יום במשך שבוע (7 ימים). בספר יש 200 עמודים. כמה עמודים קראה, וכמה נשארו לה?', [{ label: 'קראה', answer: 126 }, { label: 'נשארו', answer: 74 }], `${M('18 × 7 = 126')} ; ${M('200 − 126 = 74')}`, 'שלב 1: כמה קראה בשבוע (כפל). שלב 2: כמה נשאר (חיסור).'),
    Q.wordMulti('🧠 אתגר: לשירה ולאחיה יש יחד 96 גולות. לשירה יש פי 3 יותר גולות מלאחיה. כמה גולות יש לכל אחד?', [{ label: 'לאח', answer: 24 }, { label: 'לשירה', answer: 72 }], `לאח חלק אחד, לשירה 3 חלקים – ביחד 4 חלקים. ${M('96 ÷ 4 = 24')} לאח, ${M('24 × 3 = 72')} לשירה.`, 'ציירי: לאח ⬜, לשירה ⬜⬜⬜. כמה ריבועים ביחד? חלקי את 96 למספר הריבועים.'),
  ]);

  page('angles', '9. סוגי זוויות', [
    Q.anglePic(90, 0), Q.anglePic(40, 20), Q.anglePic(135, 10), Q.anglePic(90, 45), Q.anglePic(25, 100), Q.anglePic(150, 200),
    ...[3, 1, 5, 9, 10, 8].map((h) => Q.clock(h)),
    Q.angleObject('פינה של מחברת', 'ישרה'), Q.angleObject('קצה של משולש פיצה', 'חדה'), Q.angleObject('מחשב נייד פתוח לרווחה', 'קהה'),
    Q.angleObject('האות L', 'ישרה'), Q.angleObject('האות V', 'חדה'),
  ]);

  page('triangles', '10. סוגי משולשים', [
    Q.triSides(5, 5, 5), Q.triSides(4, 7, 4), Q.triSides(3, 5, 6), Q.triSides(8, 8, 3), Q.triSides(6, 9, 12), Q.triSides(10, 10, 10),
    Q.triDesc('במשולש יש זווית ישרה אחת ושתי זוויות חדות:', 'ישר זווית'),
    Q.triDesc('כל שלוש הזוויות במשולש חדות:', 'חד זוויות'),
    Q.triDesc('במשולש יש זווית קהה אחת ושתי זוויות חדות:', 'קהה זווית'),
    Q.triAngles(60, 60, 60), Q.triAngles(90, 45, 45), Q.triAngles(120, 30, 30), Q.triAngles(50, 60, 70), Q.triAngles(100, 40, 40), Q.triAngles(90, 30, 60),
    ...TRI_FACTS.slice(0, 4).map(([s, val, e]) => Q.trueFalse('triangles', s, val, e)),
    Q.triPicture(90, 50), Q.triPicture(60, 60), Q.triPicture(25, 125), Q.triPicture(70, 70),
  ]);

  page('mixed', 'חזרה כללית: מבחן קטן', [
    Q.wordsToDigits(6008, 'שישה אלפים ושמונה'),
    Q.succPred(5999), // the booklet asks for the successor of 5,999 – this covers both directions
    { ...Q.succPred(8000) },
    Q.digitValue(7345, 2),
    cmp(4082, 4028), cmp([9, '×', 7], [60, '+', 3]),
    Q.seqBlanks([150, 175, 200, null, null], 25),
    Q.midpoint(1000, 2000),
    Q.evalExpr([60, '−', 4, '×', '(', 3, '+', 5, ')']),
    Q.word('בחווה 145 תרנגולות. כל תרנגולת מטילה 6 ביצים בשבוע. כמה ביצים מטילות כל התרנגולות בשבוע?', 870, '145 × 6 = 870', '"כל תרנגולת" מטילה אותו מספר – כפל.', 'ביצים'),
    Q.angleTerm('זווית שגדולה מזווית ישרה נקראת:', 'קהה'),
    Q.triDesc('משולש שכל הצלעות שלו באורך שונה נקרא:', 'שונה צלעות', true),
    v(3708, 2594, '+'), v(7003, 2867, '−'), v(238, 4, '×'),
  ]);

  return pages;
}

const BOOKLET = buildBooklet();
